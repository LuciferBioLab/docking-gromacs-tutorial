"""Stage GitHub documents and build the bilingual MkDocs preview."""

import argparse
import json
import re
import shutil
import subprocess
import sys
from pathlib import Path
from tempfile import TemporaryDirectory

ROOT = Path(__file__).resolve().parents[1]
REPO = "https://github.com/LuciferBioLab/docking-gromacs-tutorial"
LINK = re.compile(r"(\]\()([^\s)]+)\)")
ENGLISH = re.compile(r"^\*\*English\*\* · \[简体中文\]\([^)]+\)$", re.M)
CHINESE = re.compile(r"^\[English\]\([^)]+\) · \*\*简体中文\*\*$", re.M)


def stage(directory):
    pairs = [json.loads(item.read_text(encoding="utf-8"))["output"]
             for item in (ROOT / "docs/source").glob("*.json")]
    paths = {
        (ROOT / path).resolve(): "index.md" if path.startswith("README") else
        Path(path.replace(".zh-CN.md", ".md")).name
        for pair in pairs for path in pair.values()
    }
    shutil.copytree(ROOT / "assets", directory / "assets")
    for image in (directory / "assets").glob("*.zh-CN.*"):
        image.rename(image.with_name(image.name.replace(".zh-CN.", ".zh.")))
    for pair in pairs:
        for locale, path in pair.items():
            source = (ROOT / path).resolve()
            document = source.read_text(encoding="utf-8")
            # The locale selector is generated by the i18n plugin.
            document = ENGLISH.sub("", CHINESE.sub("", document))
            # Render links and prose inside GitHub-style collapsible sections.
            document = document.replace("<details>", '<details markdown="1">')

            def replace(match):
                destination, separator, fragment = match[2].partition("#")
                if "://" in destination or destination.startswith("mailto:") or not destination:
                    return match[0]
                target = (source.parent / destination).resolve()
                if target in paths:
                    translated = paths[target]
                elif target.is_relative_to(ROOT / "assets"):
                    translated = target.relative_to(ROOT).as_posix().replace(".zh-CN.", ".")
                else:
                    relative = target.relative_to(ROOT).as_posix()
                    translated = f"{REPO}/blob/main/{relative}"
                return f"{match[1]}{translated}{separator}{fragment})"

            name = paths[source]
            if locale == "zh":
                name = name.replace(".md", ".zh.md")
            (directory / name).write_text(LINK.sub(replace, document), encoding="utf-8")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=ROOT / "site")
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args()
    if args.dry_run:
        print(f"Stage paired chapters and build MkDocs at {args.output}")
        return
    with TemporaryDirectory() as folder:
        workspace = Path(folder)
        content = workspace / "docs"
        content.mkdir()
        stage(content)
        config = workspace / "mkdocs.yml"
        shutil.copyfile(ROOT / "mkdocs.yml", config)
        subprocess.run(
            [sys.executable, "-m", "mkdocs", "build", "--strict", "--config-file", str(config),
             "--site-dir", str(args.output.resolve())],
            check=True,
        )


if __name__ == "__main__":
    main()
